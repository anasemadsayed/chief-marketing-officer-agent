"""
ConsultingCase — the top-level entity for one consulting engagement.

Every other domain object (CollectedSource, MarketResearch,
ExtractedCompanyInformation, BusinessDiagnosis, MarketingStrategy,
GeneratedReport) belongs to exactly one ConsultingCase via
`consulting_case_id`.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from pydantic import BaseModel, Field, HttpUrl

from domain.enums import ConsultingCaseStatus


class ConsultingCase(BaseModel):
    """
    Represents a single request from a user to analyze one company.

    The `id` is generated by the storage layer (Brick 3): a readable slug
    derived from the company name plus a guaranteed-unique suffix. It is
    never derived from the company name alone.
    """

    id: str = Field(..., description="Unique, readable consulting case identifier.")

    company_name: str = Field(..., min_length=1)

    status: ConsultingCaseStatus = ConsultingCaseStatus.CREATED

    # -- User-supplied input sources (all optional individually, but at
    # least one should be present — enforced at the application/service
    # level, not here, since the domain layer stays free of I/O and
    # cross-field business rules that belong to services). -------------
    website_url: Optional[HttpUrl] = None
    pdf_file_path: Optional[str] = None
    linkedin_url: Optional[HttpUrl] = None
    facebook_url: Optional[HttpUrl] = None
    instagram_url: Optional[HttpUrl] = None
    additional_links: list[HttpUrl] = Field(default_factory=list)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    failure_reason: Optional[str] = Field(
        default=None,
        description="Populated when status == FAILED, explaining what went wrong.",
    )

    def has_at_least_one_input_source(self) -> bool:
        """True if the user supplied anything at all to analyze."""
        return any(
            [
                self.website_url,
                self.pdf_file_path,
                self.linkedin_url,
                self.facebook_url,
                self.instagram_url,
                len(self.additional_links) > 0,
            ]
        )

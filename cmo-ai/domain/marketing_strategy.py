"""
MarketingStrategy — the evidence-based marketing strategy for one case.

Generated by the orchestrator in exactly two situations:
1. The diagnosis concluded marketing IS the primary issue, or
2. The user explicitly requested a strategy anyway, despite the
   diagnosis saying marketing is not the primary issue.

In case 2, `generated_because` and `override_warning_message` must be set
so downstream report/PowerPoint generation can surface the disclaimer
required by the spec.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from pydantic import BaseModel, Field, model_validator

from domain.enums import StrategyGenerationReason
from domain.finding import Finding


class StrategyInitiative(BaseModel):
    """One concrete, actionable piece of the overall marketing strategy."""

    title: str = Field(..., min_length=1)
    description: str = Field(..., min_length=1)
    expected_impact: str = Field(
        default="", description="What this initiative is expected to achieve, and why."
    )
    supporting_evidence: list[str] = Field(default_factory=list)


class MarketingStrategy(BaseModel):
    """The full evidence-based marketing strategy produced for a case."""

    consulting_case_id: str

    generated_because: StrategyGenerationReason

    executive_summary: str = Field(..., min_length=1)
    strategic_objectives: list[str] = Field(default_factory=list)
    recommended_channels: list[str] = Field(default_factory=list)
    key_initiatives: list[StrategyInitiative] = Field(default_factory=list)

    supporting_findings: list[Finding] = Field(default_factory=list)

    override_warning_message: Optional[str] = Field(
        default=None,
        description=(
            "Required disclaimer text when generated_because == "
            "USER_REQUESTED_STRATEGY_DESPITE_DIAGNOSIS, stating that the "
            "diagnosis found marketing is not the primary issue and this "
            "strategy exists only because the user explicitly asked for it."
        ),
    )

    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @model_validator(mode="after")
    def ensure_override_warning_present_when_required(self) -> "MarketingStrategy":
        """Enforce spec rule: an override strategy must carry its disclaimer."""
        if (
            self.generated_because
            == StrategyGenerationReason.USER_REQUESTED_STRATEGY_DESPITE_DIAGNOSIS
            and not self.override_warning_message
        ):
            raise ValueError(
                "override_warning_message is required when a strategy is "
                "generated despite the diagnosis recommending against it."
            )
        return self
